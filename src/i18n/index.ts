const dictionaries = { zh, en };
export type TranslationKey = keyof typeof zh;

export function createTranslator(language: AppLanguage) {
  return (key: TranslationKey, values?: Record<string, string | number>) => {
    const template = dictionaries[language][key] ?? zh[key];
    if (!values) return template;
    return Object.entries(values).reduce(
      (text, [name, value]) => text.split(`{${name}}`).join(String(value)),
      template,
    );
  };
}

export type Translator = ReturnType<typeof createTranslator>;

export function localeFor(language: AppLanguage) {
  return language === 'zh' ? 'zh-CN' : 'en-US';
}

export function marketLabel(language: AppLanguage, market: Market) {
  const translate = createTranslator(language);
  return translate(market === 'ashare' ? 'marketAshare' : market === 'hk' ? 'marketHk' : 'marketUs');
}

export function applyTheme(theme: AppTheme) {
  document.body.classList.toggle('theme-light', theme === 'light');
  document.body.classList.toggle('theme-dark', theme === 'dark');
}
